// Day 1: Variables, Constants, Strings, and Integers

// Variables can be changed after creation
var name = "Ted"
name = "Rebecca"

// Constants cannot be changed once set
let character = "Daphne"

// Strings
var greeting = "Hello, playground"
let quote = "Then he tapped a sign that said \"Believe\"."

// Integers
let score = 10
let higherScore = score + 10
let halvedScore = score / 2

// Compound operators
var counter = 10
counter += 5   // counter is now 15
counter -= 3   // counter is now 12
counter *= 2   // counter is now 24
